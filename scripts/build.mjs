import { readFile, mkdir, writeFile } from 'node:fs/promises';
import { Script } from 'node:vm';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
const order = JSON.parse(await readFile(path.join(root, 'source-order.json'), 'utf8'));
if (!Array.isArray(order) || new Set(order).size !== order.length) throw Error('Invalid source order');
const sources = [];
for (const file of order) {
  if (!/^src\/[a-z-]+\.js$/.test(file)) throw Error(`Invalid source file: ${file}`);
  const source = (await readFile(path.join(root, file), 'utf8')).replace(/\r\n?/g, '\n');
  new Script(source, { filename: file });
  sources.push(`// ${file}\n${source.trimEnd()}\n`);
}
// Sources share one lexical scope. Names/order are explicit in source-order.json.
const footer = '\nObject.defineProperty(module.exports, "__esModule", { value: true });\nObject.defineProperty(module.exports, "default", { enumerable: true, get: () => PMGPlugin });\n';
const output = '// Reconstructed JavaScript source; see RECONSTRUCTION.md. Generated by npm run build.\n' + sources.join('\n') + footer;
new Script(output, { filename: 'main.js' });
const destination = path.join(root, 'dist/project-milestone-gpt-tracker');
await mkdir(destination, { recursive: true });
await writeFile(path.join(destination, 'main.js'), output);
for (const file of ['manifest.json', 'styles.css']) await writeFile(path.join(destination, file), (await readFile(path.join(root, file), 'utf8')).replace(/\r\n?/g, '\n'));
console.log(`Built ${order.length} source files into dist/project-milestone-gpt-tracker`);
